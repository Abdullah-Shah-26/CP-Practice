void solve() {
  int n;
  cin >> n;

  vll a(n);
  rv(a);

  ll one = 0, ten = 0, hun = 0;

  for (int i = 0; i < n; i++) {
    ll cnt = (a[i] + 999) / 1000;
    ll change = cnt * 1000 - a[i];

    hun += change / 100;
    change %= 100;

    ten += change / 10;
    change %= 10;

    one += change;
  }

  cout << one << " " << ten << " " << hun << endl;
}

